console.log('  姿态偏差(°)   中位 '+q(ang,0.5).toFixed(1)+'  p10 '+q(ang,0.1).toFixed(1)+'  p90 '+q(ang,0.9).toFixed(1)+'  最大 '+ang[ang.length-1].toFixed(0));
