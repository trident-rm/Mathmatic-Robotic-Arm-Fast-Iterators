const fs=require('fs');
const rows=fs.readFileSync(require('../lib/paths').DATA + '/t8_ik_diag.csv','utf8').trim().split('\n').slice(1).map(l=>l.split(','));
const f=rows.filter(r=>r[7]==='0');
